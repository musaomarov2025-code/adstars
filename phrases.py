import random

# ==== Реакция на «бабка»/«бабуль» ====
def reaction_to_name(gender: str) -> str:
    внучок = "внучок" if gender == "m" else "внучка"
    phrases = [
        f"Чё тебе, {внучок}? Я семечки грызу, не видишь? 🌻",
        f"Ой, {внучок}, отстань, я занята!",
        f"Чё надо, {внучок}? Семечек хочешь? Иди на базар.",
        f"{внучок.capitalize()}, не мешай бабке сериал смотреть!",
        f"Ась? Чё, {внучок}? Громче говори, я глухая!",
        f"Тьфу ты, {внучок}, напугал бабку!",
    ]
    return random.choice(phrases)


# ==== Ответы на reply к её сообщению ====
def reply_to_babka(gender: str) -> str:
    внучок = "внучок" if gender == "m" else "внучка"
    phrases = [
        f"Чё, {внучок}, поговорить захотелось? Ну давай.",
        f"Ой, {внучок}, я тебя слушаю, слушаю...",
        f"Ну чё ты, {внучок}, как маленький?",
        f"{внучок.capitalize()}, не перебивай старших!",
        f"Иди уроки делай, {внучок}!",
        f"Чё пристал, {внучок}? У бабки давление!",
    ]
    return random.choice(phrases)


